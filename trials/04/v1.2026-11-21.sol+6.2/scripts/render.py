"""Render the reimported STEP with an offscreen VTK camera."""
from pathlib import Path

import cadquery as cq
import vtk


root = Path(__file__).resolve().parents[1]
part = cq.importers.importStep(str(root / "results" / "vacuum-adaptor.step")).val()
vertices, patches = part.tessellate(0.015, 0.06)
points = vtk.vtkPoints()
triangles = vtk.vtkCellArray()
for vertex in vertices:
    points.InsertNextPoint(*vertex.toTuple())
for ids in patches:
    triangles.InsertNextCell(len(ids), ids)
mesh = vtk.vtkPolyData()
mesh.SetPoints(points)
mesh.SetPolys(triangles)
weld = vtk.vtkCleanPolyData()
weld.SetInputData(mesh)
weld.SetTolerance(1e-8)
smooth = vtk.vtkPolyDataNormals()
smooth.SetInputConnection(weld.GetOutputPort())
smooth.SetFeatureAngle(35)
smooth.ConsistencyOn()
smooth.AutoOrientNormalsOn()
mapper = vtk.vtkPolyDataMapper()
mapper.SetInputConnection(smooth.GetOutputPort())
actor = vtk.vtkActor()
actor.SetMapper(mapper)
material = actor.GetProperty()
material.SetColor(0.22, 0.53, 0.60)
material.SetSpecular(0.16)
material.SetSpecularPower(30)
renderer = vtk.vtkRenderer()
renderer.AddActor(actor)
renderer.SetBackground(0.93, 0.95, 0.96)
renderer.SetBackground2(0.75, 0.80, 0.83)
renderer.GradientBackgroundOn()
camera = renderer.GetActiveCamera()
camera.SetFocalPoint(42, 0, 3)
camera.SetPosition(174, -228, 136)
camera.SetViewUp(0, 0, 1)
camera.ParallelProjectionOn()
camera.SetParallelScale(37)
renderer.ResetCameraClippingRange()
window = vtk.vtkRenderWindow()
window.SetOffScreenRendering(1)
window.SetSize(1440, 1000)
window.SetMultiSamples(8)
window.AddRenderer(renderer)
window.Render()
capture = vtk.vtkWindowToImageFilter()
capture.SetInput(window)
capture.Update()
writer = vtk.vtkPNGWriter()
writer.SetFileName(str(root / "renders" / "vacuum-adaptor.png"))
writer.SetInputConnection(capture.GetOutputPort())
writer.Write()
