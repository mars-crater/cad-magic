import cadquery as cq, math, os, sys
from cadquery import exporters
N=int(os.getenv('ARMS','6')); R=float(os.getenv('ARM_LENGTH','65'))
# millimeters; Z is the spinner axis; six identical swept-looking tapered blades.
body=cq.Workplane('XY').polygon(12,56).extrude(5)
for i in range(N):
 a=i*360/N
 # radial tapered panel, angled tip
 blade=(cq.Workplane('XY').polyline([(22,-8),(R-5,-7),(R, -5),(R,7),(R-5,8),(22,9)]).close().extrude(3).translate((0,0,1)))
 # tip rail aligned transversely
 rail=cq.Solid.makeCylinder(1.5,16,cq.Vector(R,-7.5,2.5),cq.Vector(0,1,0))
 blade=blade.union(rail)
 # shallow spanwise seams are genuine recessed cuts
 for x in (R-22,R-15,R-8):
  blade=blade.cut(cq.Workplane('XY').box(.55,20,.45).translate((x,0,3.85)))
 # engine pod attached to underside, axis radial; tip hollow
 pod=cq.Solid.makeCylinder(4,18,cq.Vector(31,-11,-1.5),cq.Vector(1,0,0))
 bore=cq.Solid.makeCylinder(2.8,4,cq.Vector(45,-11,-1.5),cq.Vector(1,0,0))
 p=cq.Workplane(obj=pod).cut(bore)
 strut=cq.Workplane('XY').box(6,8,3).translate((35,-7,-.2))
 blade=blade.union(p).union(strut)
 body=body.union(blade.rotate((0,0,0),(0,0,1),a))
# concentric hub, stepped disks and crown
body=body.union(cq.Workplane('XY').circle(23).extrude(1).translate((0,0,5)))
body=body.union(cq.Workplane('XY').circle(19).extrude(1).translate((0,0,6)))
# rounded dome generated by spherical cap intersection
sphere=cq.Workplane('XY').sphere(25).translate((0,0,-9))
cap=sphere.intersect(cq.Workplane('XY').box(40,40,6).translate((0,0,10)))
body=body.union(cap)
body=body.union(cq.Workplane('XY').circle(9).extrude(.5).translate((0,0,12.8)))
# ring of blind dimples
for i in range(36):
 a=2*math.pi*i/36
 body=body.cut(cq.Workplane('XY').center(21*math.cos(a),21*math.sin(a)).circle(.55).extrude(1).translate((0,0,5.5)))
shape=body.val(); print('source', 'solids',len(shape.Solids()),'valid',shape.isValid(),'volume',shape.Volume())
out=os.path.join(os.path.dirname(__file__),'spinner.step'); exporters.export(shape,out)
re=cq.importers.importStep(out).val(); b=re.BoundingBox(); print('STEP', 'solids',len(re.Solids()),'valid',re.isValid(),'volume',re.Volume(),'bbox',b.xlen,b.ylen,b.zlen)
